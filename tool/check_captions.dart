// Do caption tracks exist for videos with no HLS ladder, and can the app
// fetch them as WebVTT?
//
//   dart run tool/check_captions.dart [videoId ...]
//
// The player only offered captions read off a YouTube-issued HLS manifest,
// which about one video in eight now has, so "This video has no captions"
// appeared on videos that plainly have them. This lists each video's tracks
// through youtube_explode's closed-caption manifest and downloads one as VTT,
// so both halves — "are there tracks" and "will the file come back" — are
// measured rather than assumed.
import 'dart:io';

import 'package:http/http.dart' as http;
import 'package:youtube_explode_dart/youtube_explode_dart.dart';

Future<void> main(List<String> args) async {
  final ids = args.isEmpty ? ['dQw4w9WgXcQ', 'aqz-KE-bpKQ', 'jNQXAC9IVRw'] : args;
  final yt = YoutubeExplode();
  var ok = 0;
  for (final id in ids) {
    stdout.writeln('\n== $id');
    try {
      final manifest = await yt.videos.closedCaptions.getManifest(id);
      final tracks = manifest.tracks;
      stdout.writeln('  tracks: ${tracks.length} '
          '${tracks.take(6).map((t) => '${t.language.code}${t.isAutoGenerated ? '(auto)' : ''}').join(', ')}');
      if (tracks.isEmpty) continue;
      final url = tracks.first.url
          .replace(queryParameters: {...tracks.first.url.queryParameters, 'fmt': 'vtt'});
      final res = await http.get(url).timeout(const Duration(seconds: 15));
      final body = res.body;
      final cues = '-->'.allMatches(body).length;
      stdout.writeln('  vtt: HTTP ${res.statusCode}, ${body.length} chars, $cues cues, '
          'starts "${body.substring(0, body.length.clamp(0, 30)).replaceAll('\n', ' ')}"');
      if (res.statusCode == 200 && cues > 0) ok++;
    } catch (e) {
      stdout.writeln('  FAILED: $e'.split('\n').first);
    }
  }
  yt.close();
  stdout.writeln('\nSUMMARY: usable VTT for $ok/${ids.length} videos');
  if (ok == 0) exitCode = 1;
}
